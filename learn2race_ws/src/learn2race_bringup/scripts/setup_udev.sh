#!/usr/bin/env bash

# References (full entries: docs/references.md at the repository root):
#   [R92] udev rules: udev rules
# More details: README.md of this package

# Stable device names for a Learn2Race robot: /dev/mcu and /dev/lidar.
#
# Both the ESP32 board and the LiDAR appear as USB serial ports, and Linux
# numbers them ttyUSB0, ttyUSB1 ... in whatever order they enumerate at boot.
# Code that opens ttyUSB0 therefore sometimes talks to the LiDAR instead of the
# micro-ROS client, and the agent fails with no useful error. A udev rule gives
# each device a fixed name that does not depend on enumeration order.
#
# Identification is by unplugging: the script records the ports present, asks
# you to unplug one device, and the port that disappears is that device. This
# works even when both devices use the same USB-serial chip, which is common
# here since the LiDAR adapter and the driver board may both be CP2102.
#
#   sudo ./setup_udev.sh

set -euo pipefail
RULES=/etc/udev/rules.d/99-learn2race.rules

if [[ $EUID -ne 0 ]]; then
  echo "Run with sudo."; exit 1
fi

ports () { ls /dev/ttyUSB* /dev/ttyACM* 2>/dev/null | sort || true; }

attr () {  # attr <device> <property>
  udevadm info --query=property --name="$1" | sed -n "s/^$2=//p"
}

identify () {  # identify <label>
  local label="$1" before after gone
  read -rp "  With everything plugged in, press Enter. " _
  before=$(ports)
  if [[ -z "$before" ]]; then
    echo "  No USB serial ports found. Check cables and power, then retry." >&2; return 1
  fi
  read -rp "  Now UNPLUG the $label, wait two seconds, press Enter. " _
  sleep 1
  after=$(ports)
  gone=$(comm -23 <(echo "$before") <(echo "$after"))
  if [[ $(echo "$gone" | grep -c . || true) -ne 1 ]]; then
    echo "  Expected exactly one port to disappear, got: '${gone}'. Retry." >&2; return 1
  fi
  read -rp "  Plug the $label back in, wait two seconds, press Enter. " _
  sleep 1
  echo "$gone"
}

rule_for () {  # rule_for <device> <symlink>
  local dev="$1" name="$2" vid pid serial path
  vid=$(attr "$dev" ID_VENDOR_ID); pid=$(attr "$dev" ID_MODEL_ID)
  serial=$(attr "$dev" ID_SERIAL_SHORT); path=$(attr "$dev" ID_PATH)

  # Prefer the chip serial number, which follows the device to any USB port.
  # Fall back to the physical port path when the serial is missing or is one of
  # the placeholder values cheap USB-serial clones share, since two devices with
  # the same serial cannot be told apart by it.
  local shared=0
  for other in $(ports); do
    [[ "$other" == "$dev" ]] && continue
    [[ -n "$serial" && "$(attr "$other" ID_SERIAL_SHORT)" == "$serial" ]] && shared=1
  done
  if [[ -n "$serial" && "$serial" != "0001" && $shared -eq 0 ]]; then
    echo "SUBSYSTEM==\"tty\", ENV{ID_VENDOR_ID}==\"$vid\", ENV{ID_MODEL_ID}==\"$pid\", ENV{ID_SERIAL_SHORT}==\"$serial\", SYMLINK+=\"$name\", MODE=\"0666\""
    echo "  $name: matched by serial $serial (works on any USB port)" >&2
  else
    echo "SUBSYSTEM==\"tty\", ENV{ID_PATH}==\"$path\", SYMLINK+=\"$name\", MODE=\"0666\""
    echo "  $name: matched by USB port $path (keep it plugged into THIS port)" >&2
  fi
}

echo "Learn2Race device naming"
echo
echo "Step 1: the ESP32 driver board (the micro-ROS client)."
mcu=$(identify "ESP32 driver board") || exit 1
echo "  -> $mcu"
echo
lidar=""
read -rp "Is a LiDAR connected by USB? [y/N] " yn
if [[ "$yn" =~ ^[Yy] ]]; then
  echo "Step 2: the LiDAR."
  lidar=$(identify "LiDAR") || exit 1
  echo "  -> $lidar"
fi

{
  echo "# Learn2Race stable device names. Generated by setup_udev.sh."
  rule_for "$mcu" mcu
  [[ -n "$lidar" ]] && rule_for "$lidar" lidar
} > "$RULES"

udevadm control --reload-rules
udevadm trigger --subsystem-match=tty
sleep 1

echo
echo "Written $RULES:"
cat "$RULES"
echo
ls -l /dev/mcu /dev/lidar 2>/dev/null || true
echo
echo "Start the agent with --dev /dev/mcu. Launch files default to these names."
